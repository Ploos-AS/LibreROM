/* LibreROM M2.12 Macintosh Plus GCR sector-0 loader.
 * Project-authored clean-room firmware code.
 *
 * Extends M2.11 from raw IWM byte capture to a minimal sector loader:
 * - verify media present through IWM sense bank 8
 * - start drive 1 and enter IWM read-data mode
 * - locate a Macintosh GCR data address mark (D5 AA AD)
 * - require sector 0
 * - translate 703 GCR symbols into 527 checksum-domain bytes
 * - reverse the Macintosh GCR rolling checksum transform
 * - validate the three checksum bytes
 * - copy the 512-byte sector payload to RAM at 0x00002000
 *
 * Qualification media is generated by this project and contains no Apple
 * ROM, System software, or derived proprietary material.
 */

        .section .vectors,"a"
        .globl _m2_12_vectors
_m2_12_vectors:
        .long   0x00100000
        .long   _m2_12_reset

        .section .text,"ax"
        .globl _m2_12_reset
_m2_12_reset:
        move.w  #0x2700,%sr

        /* Non-destructive top-of-RAM probe. */
        move.l  #0x006ffffc,%a0
        move.l  (%a0),%d3
        move.l  #0xa55aa55a,(%a0)
        move.l  (%a0),%d2
        cmpi.l  #0xa55aa55a,%d2
        bne.w   _m2_12_ram_fail_alt
        move.l  %d3,(%a0)

        /* Install full RAM vector table before overlay removal. */
        move.l  #0x00600000,%a0
        move.l  #0x00100000,(%a0)+
        move.l  #_m2_12_reset,(%a0)+
        move.l  #_m2_12_default,%d0
        move.w  #253,%d1
1:
        move.l  %d0,(%a0)+
        dbra    %d1,1b

        move.l  #0x00600064,%a0
        move.l  #_m2_12_via_irq,(%a0)

        move.l  #0x00600408,%a0
        move.l  #0x50523132,(%a0)       /* PR12 */

        .globl _m2_12_before_overlay_off
_m2_12_before_overlay_off:
        move.l  #0x00efe600,%a0
        move.b  (%a0),%d0
        ori.b   #0x10,%d0
        move.b  %d0,(%a0)

        move.l  #0x00efe200,%a0
        move.b  (%a0),%d0
        andi.b  #0xef,%d0
        move.b  %d0,(%a0)

        move.l  #0x00000000,%a0
        move.l  (%a0)+,%d2
        cmpi.l  #0x00100000,%d2
        bne.w   _m2_12_ram_fail_low
        move.l  (%a0),%d2
        cmpi.l  #_m2_12_reset,%d2
        bne.w   _m2_12_ram_fail_low

        move.l  #0x00000400,%a0
        move.l  #0x4c523132,(%a0)       /* LR12 */
        move.l  #0x000f0000,%a7
        trap    #0

        /* Preserve framebuffer regression. */
        move.w  #0xaa55,%d0
        move.w  #10943,%d1
        move.l  #0x000fa700,%a0
2:
        move.w  %d0,(%a0)+
        dbra    %d1,2b
        move.w  #10943,%d1
        move.l  #0x000f2700,%a0
3:
        move.w  %d0,(%a0)+
        dbra    %d1,3b
        move.l  #0x0000040c,%a0
        move.l  #0x56493132,(%a0)       /* VI12 */

        /* Preserve M2.9 keyboard query regression. */
        move.l  #0x00effc00,%a0
        move.b  #0x7f,(%a0)
        move.l  #0x00effa00,%a0
        move.b  #0x04,(%a0)
        move.l  #0x00eff600,%a0
        move.b  (%a0),%d0
        andi.b  #0xe3,%d0
        ori.b   #0x1c,%d0
        move.b  %d0,(%a0)
        move.l  #0x00eff400,%a0
        move.b  #0x16,(%a0)
        move.l  #0x00eff600,%a0
        move.b  (%a0),%d0
        andi.b  #0xe3,%d0
        ori.b   #0x0c,%d0
        move.b  %d0,(%a0)
        move.l  #0x00effc00,%a0
        move.b  #0x84,(%a0)
        move.w  #0x2000,%sr
_m2_12_wait_keyboard:
        move.l  0x0000041c,%d0
        cmpi.l  #0x4b423132,%d0         /* KB12 */
        bne.w   _m2_12_wait_keyboard
        move.w  #0x2700,%sr
        move.l  #0x00effc00,%a0
        move.b  #0x04,(%a0)
        move.l  #0x00000420,%a0
        move.l  #0x494e3132,(%a0)       /* IN12 */

        /* IWM media sense bank 8. */
        move.l  #0x00efe600,%a0
        move.b  (%a0),%d6
        move.b  %d6,%d0
        ori.b   #0x20,%d0
        move.b  %d0,(%a0)

        move.l  #0x00efe200,%a0
        move.b  (%a0),%d0
        andi.b  #0xdf,%d0
        move.b  %d0,(%a0)
        ori.b   #0x20,%d0
        move.b  %d0,(%a0)

        move.b  0x00c00001,%d0
        move.b  0x00c00401,%d0
        move.b  0x00c00801,%d0
        move.b  0x00c01c01,%d0
        move.b  0x00c01a01,%d0
        move.l  #0x00000424,%a0
        move.b  %d0,(%a0)
        btst    #7,%d0
        bne.w   _m2_12_no_media

        move.l  #0x00000428,%a0
        move.l  #0x49574d50,(%a0)       /* IWMP */

        /* Head 0, motor on, ENABLE=1, Q6=Q7=0 read-data mode. */
        move.l  #0x00efe200,%a0
        move.b  (%a0),%d0
        andi.b  #0xdf,%d0
        move.b  %d0,(%a0)

        move.b  0x00c00001,%d0         /* CA0 low */
        move.b  0x00c00601,%d0         /* CA1 high: control register 2 */
        move.b  0x00c00801,%d0         /* CA2 low: motor on */
        move.b  0x00c00e01,%d0         /* LSTRB high */
        move.b  0x00c00c01,%d0         /* LSTRB low */
        move.b  0x00c01201,%d0         /* ENABLE high */
        move.b  0x00c01801,%d0         /* Q6 low */
        move.b  0x00c01c01,%d0         /* Q7 low */

        /* Locate a data address mark D5 AA AD within a bounded raw stream. */
        moveq   #0,%d3
        move.l  #12000,%d6
_m2_12_find_dam:
        bsr.w   _m2_12_get_iwm_byte
        tst.l   %d0
        bmi.w   _m2_12_read_fail
        lsl.l   #8,%d3
        move.b  %d0,%d3
        andi.l  #0x00ffffff,%d3
        cmpi.l  #0x00d5aaad,%d3
        beq.s   _m2_12_dam_found
        subq.l  #1,%d6
        bne.w   _m2_12_find_dam
        bra.w   _m2_12_read_fail

_m2_12_dam_found:
        /* First translated symbol after DAM is sector number; require 0. */
        bsr.w   _m2_12_get_gcr_symbol
        tst.l   %d0
        bmi.w   _m2_12_read_fail
        tst.b   %d0
        bne.w   _m2_12_read_fail

        /* Reconstruct 527 checksum-domain bytes at 0x00000800. */
        move.l  #0x00000800,%a1
        move.w  #173,%d4               /* 174 groups = 522 bytes */
_m2_12_decode_groups:
        bsr.w   _m2_12_get_gcr_symbol
        tst.l   %d0
        bmi.w   _m2_12_read_fail
        lsl.l   #2,%d0
        move.l  %d0,%d7

        bsr.w   _m2_12_get_gcr_symbol
        tst.l   %d0
        bmi.w   _m2_12_read_fail
        move.l  %d7,%d2
        andi.l  #0x000000c0,%d2
        or.b    %d2,%d0
        move.b  %d0,(%a1)+
        lsl.l   #2,%d7

        bsr.w   _m2_12_get_gcr_symbol
        tst.l   %d0
        bmi.w   _m2_12_read_fail
        move.l  %d7,%d2
        andi.l  #0x000000c0,%d2
        or.b    %d2,%d0
        move.b  %d0,(%a1)+
        lsl.l   #2,%d7

        bsr.w   _m2_12_get_gcr_symbol
        tst.l   %d0
        bmi.w   _m2_12_read_fail
        move.l  %d7,%d2
        andi.l  #0x000000c0,%d2
        or.b    %d2,%d0
        move.b  %d0,(%a1)+
        dbra    %d4,_m2_12_decode_groups

        /* Final two bytes of the 524-byte checksum-domain body. */
        bsr.w   _m2_12_get_gcr_symbol
        tst.l   %d0
        bmi.w   _m2_12_read_fail
        lsl.l   #2,%d0
        move.l  %d0,%d7

        bsr.w   _m2_12_get_gcr_symbol
        tst.l   %d0
        bmi.w   _m2_12_read_fail
        move.l  %d7,%d2
        andi.l  #0x000000c0,%d2
        or.b    %d2,%d0
        move.b  %d0,(%a1)+
        lsl.l   #2,%d7

        bsr.w   _m2_12_get_gcr_symbol
        tst.l   %d0
        bmi.w   _m2_12_read_fail
        move.l  %d7,%d2
        andi.l  #0x000000c0,%d2
        or.b    %d2,%d0
        move.b  %d0,(%a1)+

        /* Three checksum bytes share one high-bits symbol. */
        bsr.w   _m2_12_get_gcr_symbol
        tst.l   %d0
        bmi.w   _m2_12_read_fail
        lsl.l   #2,%d0
        move.l  %d0,%d7

        bsr.w   _m2_12_get_gcr_symbol
        tst.l   %d0
        bmi.w   _m2_12_read_fail
        move.l  %d7,%d2
        andi.l  #0x000000c0,%d2
        or.b    %d2,%d0
        move.b  %d0,(%a1)+
        lsl.l   #2,%d7

        bsr.w   _m2_12_get_gcr_symbol
        tst.l   %d0
        bmi.w   _m2_12_read_fail
        move.l  %d7,%d2
        andi.l  #0x000000c0,%d2
        or.b    %d2,%d0
        move.b  %d0,(%a1)+
        lsl.l   #2,%d7

        bsr.w   _m2_12_get_gcr_symbol
        tst.l   %d0
        bmi.w   _m2_12_read_fail
        move.l  %d7,%d2
        andi.l  #0x000000c0,%d2
        or.b    %d2,%d0
        move.b  %d0,(%a1)+

        /* Reverse PCE's documented Macintosh rolling checksum transform. */
        move.l  #0x00000800,%a1
        move.l  #0x00001000,%a2
        moveq   #0,%d1                 /* chk0 */
        moveq   #0,%d2                 /* chk1 */
        moveq   #0,%d3                 /* chk2 */
        move.w  #173,%d4               /* 174 * 3 = 522 bytes */
_m2_12_checksum_groups:
        bsr.w   _m2_12_checksum_rotate
        bsr.w   _m2_12_checksum_byte
        bsr.w   _m2_12_checksum_byte
        bsr.w   _m2_12_checksum_byte
        dbra    %d4,_m2_12_checksum_groups

        /* Bytes 522 and 523 form the final partial group. */
        bsr.w   _m2_12_checksum_rotate
        bsr.w   _m2_12_checksum_byte
        bsr.w   _m2_12_checksum_byte
        andi.l  #0x000000ff,%d3

        /* Validate checksum bytes 524..526. */
        moveq   #0,%d0
        move.b  (%a1)+,%d0
        cmp.b   %d2,%d0
        bne.w   _m2_12_checksum_fail
        moveq   #0,%d0
        move.b  (%a1)+,%d0
        cmp.b   %d3,%d0
        bne.w   _m2_12_checksum_fail
        moveq   #0,%d0
        move.b  (%a1)+,%d0
        cmp.b   %d1,%d0
        bne.w   _m2_12_checksum_fail

        /* Copy 512-byte sector payload (skip 12 tags) to loader RAM. */
        move.l  #0x0000100c,%a0
        move.l  #0x00002000,%a1
        move.w  #127,%d4
_m2_12_copy_payload:
        move.l  (%a0)+,(%a1)+
        dbra    %d4,_m2_12_copy_payload

        move.l  #0x00002000,%a0
        cmpi.l  #0x4c523132,(%a0)       /* fixture begins LR12 */
        bne.w   _m2_12_payload_fail

        move.l  #0x00000440,%a0
        move.l  #0x53454332,(%a0)       /* SEC2 */
        move.l  #0x00000444,%a0
        move.l  #0x43484b32,(%a0)       /* CHK2 */
        bra.s   _m2_12_read_done

_m2_12_checksum_fail:
        move.l  #0x00000444,%a0
        move.l  #0x434b4632,(%a0)       /* CKF2 */
        bra.s   _m2_12_read_fail_mark

_m2_12_payload_fail:
        move.l  #0x00000444,%a0
        move.l  #0x504c4632,(%a0)       /* PLF2 */
        bra.s   _m2_12_read_fail_mark

_m2_12_read_fail:
        move.l  #0x00000444,%a0
        move.l  #0x52444632,(%a0)       /* RDF2 */
_m2_12_read_fail_mark:
        move.l  #0x00000440,%a0
        move.l  #0x46414932,(%a0)       /* FAI2 */

_m2_12_read_done:
        move.l  #0x0000042c,%a0
        move.l  #0x49574d32,(%a0)       /* IWM2 */

        /* Stop drive and restore VIA direction. */
        move.b  0x00c01001,%d0         /* ENABLE low */
        move.b  0x00c00001,%d0
        move.b  0x00c00601,%d0
        move.b  0x00c00a01,%d0         /* CA2 high: motor off */
        move.b  0x00c00e01,%d0
        move.b  0x00c00c01,%d0
        move.l  #0x00efe600,%a0
        move.b  %d6,(%a0)
        bra.w   _m2_12_stop

_m2_12_no_media:
        move.l  #0x00000428,%a0
        move.l  #0x49574d4e,(%a0)       /* IWMN */
        move.l  #0x00000440,%a0
        move.l  #0x4e4f4432,(%a0)       /* NOD2 */
        move.l  #0x0000042c,%a0
        move.l  #0x49574d32,(%a0)       /* IWM2 */
        move.l  #0x00efe200,%a0
        move.b  (%a0),%d0
        andi.b  #0xdf,%d0
        move.b  %d0,(%a0)
        move.l  #0x00efe600,%a0
        move.b  %d6,(%a0)
        bra.w   _m2_12_stop

/* Return next IWM data byte (high bit set) in D0, or -1 on timeout. */
_m2_12_get_iwm_byte:
        move.l  #0x00010000,%d5
4:
        moveq   #0,%d0
        move.b  0x00c01801,%d0
        btst    #7,%d0
        bne.s   5f
        subq.l  #1,%d5
        bne.s   4b
        moveq   #-1,%d0
5:
        rts

/* Translate one GCR byte through the 64-entry clean-room table. */
_m2_12_get_gcr_symbol:
        bsr.s   _m2_12_get_iwm_byte
        tst.l   %d0
        bmi.s   8f
        lea     _m2_12_gcr_table(%pc),%a3
        moveq   #0,%d2
6:
        cmp.b   (%a3)+,%d0
        beq.s   7f
        addq.l  #1,%d2
        cmpi.l  #64,%d2
        bne.s   6b
        moveq   #-1,%d0
        rts
7:
        move.l  %d2,%d0
8:
        rts

/* chk2 = rotate-left-through-nine-bits(chk2), matching PCE decoder. */
_m2_12_checksum_rotate:
        move.l  %d3,%d7
        lsr.l   #7,%d7
        andi.l  #1,%d7
        lsl.l   #1,%d3
        andi.l  #0x000001fe,%d3
        or.l    %d7,%d3
        rts

/* Decode one checksum-domain byte from (A1)+ to (A2)+ and rotate chk0..2. */
_m2_12_checksum_byte:
        moveq   #0,%d0
        move.b  (%a1)+,%d0
        move.l  %d3,%d7
        andi.l  #0x000000ff,%d7
        eor.b   %d7,%d0
        andi.l  #0x000000ff,%d0
        move.l  %d3,%d7
        lsr.l   #8,%d7
        andi.l  #1,%d7
        add.l   %d0,%d1
        add.l   %d7,%d1
        andi.l  #0x000000ff,%d3
        move.b  %d0,(%a2)+
        move.l  %d1,%d7
        move.l  %d2,%d1
        move.l  %d3,%d2
        move.l  %d7,%d3
        rts

        .globl _m2_12_stop
_m2_12_stop:
        stop    #0x2700
        bra.w   _m2_12_stop

_m2_12_ram_fail_alt:
        move.l  #0x00600400,%a0
        move.l  #0x52413132,(%a0)       /* RA12 */
        stop    #0x2700
        bra.w   _m2_12_ram_fail_alt

_m2_12_ram_fail_low:
        move.l  #0x00000400,%a0
        move.l  #0x524d3132,(%a0)       /* RM12 */
        stop    #0x2700
        bra.w   _m2_12_ram_fail_low

        .globl _m2_12_default
_m2_12_default:
        move.l  #0x00000404,%a0
        move.l  #0x45583132,(%a0)       /* EX12 */
        rte

        .globl _m2_12_via_irq
_m2_12_via_irq:
        move.l  #0x00effa00,%a0
        move.b  (%a0),%d0
        andi.b  #0x04,%d0
        beq.w   _m2_12_via_irq_done
        move.l  #0x00eff400,%a0
        move.b  (%a0),%d0
        move.l  #0x00000418,%a0
        move.b  %d0,(%a0)
        move.l  #0x0000041c,%a0
        move.l  #0x4b423132,(%a0)       /* KB12 */
_m2_12_via_irq_done:
        rte

        .section .rodata,"a"
        .balign 4
_m2_12_marker:
        .ascii  "LIBREROM-M2.12-MACPLUS-GCR-SECTOR0\0"

_m2_12_gcr_table:
        .byte 0x96,0x97,0x9a,0x9b,0x9d,0x9e,0x9f,0xa6
        .byte 0xa7,0xab,0xac,0xad,0xae,0xaf,0xb2,0xb3
        .byte 0xb4,0xb5,0xb6,0xb7,0xb9,0xba,0xbb,0xbc
        .byte 0xbd,0xbe,0xbf,0xcb,0xcd,0xce,0xcf,0xd3
        .byte 0xd6,0xd7,0xd9,0xda,0xdb,0xdc,0xdd,0xde
        .byte 0xdf,0xe5,0xe6,0xe7,0xe9,0xea,0xeb,0xec
        .byte 0xed,0xee,0xef,0xf2,0xf3,0xf4,0xf5,0xf6
        .byte 0xf7,0xf9,0xfa,0xfb,0xfc,0xfd,0xfe,0xff
